# azd postprovision：
# 1. 按 digest 把四个发布镜像复制到 ACR（服务端复制，镜像不经过本机）；
# 2. Key Vault 中缺少的生成类机密：随机生成并经 ARM 写入（已存在的不动）；
# 3. 报告还需要运维写入的机密；
# 4. 运行 MySQL 账号初始化 Job（k8s/mysql-bootstrap，可重复执行）；
# 5. 配置已确认时部署应用（hooks/deploy-app.ps1）。
# 可以重复执行：azd hooks run postprovision。
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/common.ps1"
Import-AzdEnvironment

# ---- 1. 镜像 ----
$registry = Get-RequiredEnv 'AZURE_CONTAINER_REGISTRY_NAME'
$manifest = Get-Content -Raw (Join-Path $script:AzureDir 'images.json') | ConvertFrom-Json
Write-Host "postprovision: importing $($manifest.tag) into $registry (by digest)"
foreach ($property in $manifest.images.PSObject.Properties) {
  $arguments = @('acr', 'import', '--name', $registry, '--source', $property.Value, '--image', "ghcp/$($property.Name):$($manifest.tag)", '--force')
  # 可选：Docker Hub 账号，避免匿名拉取限额（令牌只从环境变量读取）。
  if ($env:GHCP_DOCKERHUB_USERNAME -and $env:GHCP_DOCKERHUB_TOKEN) {
    $arguments += @('--username', $env:GHCP_DOCKERHUB_USERNAME, '--password', $env:GHCP_DOCKERHUB_TOKEN)
  }
  Invoke-Az -Arguments $arguments | Out-Null
  Write-Host "  ghcp/$($property.Name)@$(($property.Value -split '@')[1])"
}

# ---- 2. 生成类机密 ----
Write-Host 'postprovision: Key Vault secrets generated by this deployment'
Initialize-GeneratedSecret 'ghcp-internal-api-token' | Out-Null
Initialize-GeneratedSecret 'ghcp-session-secret' | Out-Null
Initialize-GeneratedSecret 'ghcp-proxy-api-key' | Out-Null
Initialize-GeneratedSecret 'ghcp-sso-default-user-password' 24 | Out-Null

# MYSQL_URL 与 Proxy 账号密码一起生成：Key Vault 数据面不可达时读不回已有密码，只能成对生成。
# 账号初始化 Job 会把 MySQL 中的账号密码设为这里的值，两者保持一致。
$mysqlUrlCreated = $false
if (-not (Test-KeyVaultSecret 'ghcp-mysql-url')) {
  $password = New-RandomSecret 32
  $user = if ($env:GHCP_MYSQL_PROXY_USER) { $env:GHCP_MYSQL_PROXY_USER } else { 'ghcp_proxy' }
  $url = "mysql://${user}:$([Uri]::EscapeDataString($password))@$(Get-RequiredEnv 'MYSQL_FQDN'):3306/$(Get-RequiredEnv 'MYSQL_DATABASE')"
  Set-KeyVaultSecretViaArm -Name 'ghcp-mysql-proxy-password' -Value $password
  Set-KeyVaultSecretViaArm -Name 'ghcp-mysql-url' -Value $url
  Remove-Variable password, url
  $mysqlUrlCreated = $true
  Write-Host '  ghcp-mysql-proxy-password, ghcp-mysql-url generated'
} else {
  Write-Host '  ghcp-mysql-url exists, kept'
}

# ---- 3. 运维提供的机密 ----
$operatorSecrets = @('ghcp-scim-token', 'ghcp-copilot-seat-pat', 'ghcp-saml-idp-cert', 'ghcp-saml-idp-key')
if (Test-EnvTrue 'GHCP_PUBLIC_ACCESS_ENABLED') { $operatorSecrets += 'ghcp-public-tls (or the certificateNames in GHCP_PUBLIC_ACCESS)' }
$missing = @($operatorSecrets | Where-Object { $_ -match ' ' -or -not (Test-KeyVaultSecret $_) })
if ($missing.Count) {
  Write-Warning ("Key Vault still needs these operator-provided secrets: " + ($missing -join ', ') +
    ". Write them with deploy/azure/hooks/Set-GhcpSecret.ps1 (README section 5.2). SSO stays at ContainerCreating until they exist.")
}

# ---- 4. MySQL 账号 ----
$bootstrap = Test-EnvTrue 'GHCP_MYSQL_BOOTSTRAP' $true
if ($bootstrap) {
  Write-Host 'postprovision: MySQL account bootstrap'
  if ((Invoke-Renderer @('render')) -ne 0) { throw 'Rendering the overlays failed (see the errors above).' }
  Connect-Aks
  $namespace = Get-RequiredEnv 'GHCP_NAMESPACE'
  Initialize-Namespace $namespace
  Invoke-Kubectl -Arguments @('-n', $namespace, 'delete', 'job', 'ghcp-mysql-bootstrap', '--ignore-not-found') | Out-Null
  Invoke-Kubectl -Arguments @('apply', '-k', (Join-Path (Get-GeneratedDir) 'mysql-bootstrap')) | Out-Null
  Invoke-Kubectl -Arguments @('-n', $namespace, 'wait', '--for=condition=complete', 'job/ghcp-mysql-bootstrap', '--timeout=600s') -AllowFailure | Out-Null
  $succeeded = $LASTEXITCODE -eq 0
  Invoke-Kubectl -Arguments @('-n', $namespace, 'logs', 'job/ghcp-mysql-bootstrap', '--tail=50') -AllowFailure
  if (-not $succeeded) {
    throw 'The MySQL bootstrap job did not complete. Check: kubectl describe job/ghcp-mysql-bootstrap, and that mysql-admin-password / ghcp-mysql-proxy-password exist in Key Vault.'
  }
} elseif ($mysqlUrlCreated) {
  Write-Warning 'GHCP_MYSQL_BOOTSTRAP=false: create the Proxy MySQL account yourself with the password in Key Vault secret ghcp-mysql-proxy-password (README section 5.3).'
}

$egress = [Environment]::GetEnvironmentVariable('NAT_EGRESS_IP')
if ($egress) { Write-Host "Outbound traffic to GitHub / Copilot leaves from $egress (NAT Gateway); add it to IP allow lists where required." }

# ---- 5. 应用（只有 GHCP_CONFIG_APPROVED=true 时部署；否则打印配置摘要供核对）----
& "$PSScriptRoot/deploy-app.ps1" -IfApproved
Write-Host 'postprovision: done'
